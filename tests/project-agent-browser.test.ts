import { createServer } from 'node:http';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { expect, it } from 'vitest';
import { writeAiSettings } from '../src/ai/model.js';
import { runCheck } from '../src/check/run.js';
import { startConsole } from '../src/ui/server.js';
import { addProject, saveRound, shotsDir, updateRound } from '../src/ui/store.js';

it('opens the same project-specific repair chat from navigation and a finding', async () => {
  const home = await mkdtemp(join(tmpdir(), 'uxqa-agent-ui-home-'));
  const workspace = await mkdtemp(join(tmpdir(), 'uxqa-agent-ui-project-'));
  const prior = process.env.UXQA_HOME;
  process.env.UXQA_HOME = home;
  await writeFile(join(home, 'access-settings.json'), JSON.stringify({ locale: 'en', onboardingDone: true, checks: [] }));
  const requests: string[] = [];
  const actions: object[] = [];
  const model = createServer(async (request, response) => { let body = ''; for await (const chunk of request) body += chunk; requests.push(body); response.setHeader('content-type', 'application/json'); response.end(JSON.stringify({ choices: [{ message: { content: JSON.stringify(actions.shift() ?? { type: 'answer', text: 'Use the project color token and recheck.' }) } }] })); });
  await new Promise<void>((done) => model.listen(0, '127.0.0.1', done));
  const address = model.address();
  if (!address || typeof address === 'string') throw new Error('Expected local fixture model');
  const firstRoot = join(workspace, 'first'), secondRoot = join(workspace, 'second');
  await mkdir(join(firstRoot, 'src'), { recursive: true }); await mkdir(join(secondRoot, 'src'), { recursive: true });
  await writeFile(join(firstRoot, 'src', 'Screen.tsx'), 'export function Screen(){return <button style={{color:"#ff0000"}}>Save</button>}');
  await writeFile(join(secondRoot, 'src', 'Screen.tsx'), 'export function Screen(){return <button>Other</button>}');
  const first = await addProject(firstRoot, 'First project');
  await addProject(secondRoot, 'Second project');
  const round = await saveRound(first.id, await runCheck({ source: firstRoot }));
  await mkdir(shotsDir(first.id, round.id), { recursive: true });
  const screenshotPath = join(shotsDir(first.id, round.id), 'view-1234567890.png');
  await writeFile(screenshotPath, Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/aX8AAAAASUVORK5CYII=', 'base64'));
  round.capture = { baseUrl: 'http://127.0.0.1', viewport: 'desktop', pages: [], captures: {}, views: [{ route: '/', width: 1440, image: screenshotPath }], cancelled: false, durationMs: 1 };
  await updateRound(first.id, round);
  await writeAiSettings({ mode: 'api', protocol: 'openai', connection: 'direct', baseUrl: `http://127.0.0.1:${address.port}/v1`, model: 'fixture', passes: 1, verify: false, discover: false, maxCalls: 8 });
  const server = await startConsole({ port: 0 });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const consoleErrors: string[] = [];
  page.on('console', (entry) => { if (entry.type() === 'error') consoleErrors.push(entry.text()); });
  try {
    await page.goto(server.url);
    await page.getByRole('tab', { name: 'Repair chat', exact: true }).click();
    await page.getByText(/Screenshots are attached by default/).waitFor();
    const attach = page.getByRole('checkbox', { name: 'Attach a finding screenshot or page overview' });
    expect(await attach.isEnabled()).toBe(true);
    expect(await attach.isChecked()).toBe(true);
    await page.getByText('Motion measurement options', { exact: true }).click();
    const allowClick = page.getByRole('checkbox', { name: /Allow page clicks for this motion measurement/ });
    expect(await allowClick.isChecked()).toBe(false);
    await allowClick.check();
    await page.getByLabel('Message the project agent').fill('How should I fix this page?');
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await page.getByText('Use the project color token and recheck.').waitFor();
    expect(requests[0]).toContain('data:image/png;base64,');
    expect(await attach.isChecked()).toBe(true);
    expect(await allowClick.isChecked()).toBe(false);
    actions.push({ type: 'list', path: 'src' }, { type: 'design_candidate', candidate: { name: 'Project candidate', basis: 'Existing button', typography: 'Existing type', spacing: 'Existing scale', unknowns: 'Rendered page', colors: { background: '#ffffff', foreground: '#777777', primary: '#000000', onPrimary: '#ffffff' } } }, { type: 'answer', text: 'Candidate ready.' });
    await page.getByLabel('Message the project agent').fill('Propose a candidate');
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await page.getByText('Design-system candidate (not applied)').waitFor();
    await page.getByText('No project excerpt read this turn was cited; the design basis is unverified.').waitFor();
    await page.getByText(/below 4.5:1 for normal text/).waitFor();
    expect(await page.locator('.agent-swatch').count()).toBe(4);
    expect(await page.locator('.agent-swatch').first().evaluate((element) => getComputedStyle(element).backgroundColor)).toBe('rgb(255, 255, 255)');
    expect(consoleErrors).toEqual([]);
    const desktopSendBox = await page.getByRole('button', { name: 'Send', exact: true }).boundingBox();
    expect(desktopSendBox && desktopSendBox.y + desktopSendBox.height).toBeLessThanOrEqual(900);
    await page.getByText('View candidate CSS').click();
    await page.getByText(/--candidate-background/).waitFor();
    actions.push({ type: 'read', path: 'src/Screen.tsx' }, { type: 'design_candidate', candidate: { name: 'Evidence candidate', basis: 'Screen button', typography: 'Existing type', spacing: 'Existing scale', unknowns: 'Rendered page', sourceEvidence: [{ path: 'src/Screen.tsx', excerpt: 'color:"#ff0000"' }], colors: { background: '#ffffff', foreground: '#111111', primary: '#000000', onPrimary: '#ffffff', surface: '#eeeeee', onSurface: '#111111', warning: '#ffff00' }, scales: { fontSize: { body: '1rem' }, space: { medium: '16px' } } } }, { type: 'answer', text: 'Evidence candidate ready.' });
    await page.getByLabel('Message the project agent').fill('Show the evidence for another candidate');
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await page.getByText('Evidence candidate ready.').waitFor();
    const evidenceCard = page.locator('.agent-message').filter({ hasText: 'Evidence candidate' }).filter({ has: page.getByText('View project evidence read this turn') });
    await evidenceCard.getByText('View project evidence read this turn').click();
    await evidenceCard.getByText('src/Screen.tsx:1').waitFor();
    await evidenceCard.getByText('View candidate tokens').click();
    await evidenceCard.getByText(/fontSize: body = 1rem/).waitFor();
    await evidenceCard.getByText(/Missing paired colors; contrast not calculated/).waitFor();
    await evidenceCard.getByText('View candidate CSS').click();
    const css = await evidenceCard.locator('pre').filter({ hasText: '--candidate-font-size-body' }).innerText();
    const parsed = await page.evaluate((text) => { const sheet = new CSSStyleSheet(); sheet.replaceSync(text); return (sheet.cssRules[0] as CSSStyleRule).style.getPropertyValue('--candidate-font-size-body').trim(); }, css);
    expect(parsed).toBe('1rem');
    await page.getByRole('tab', { name: 'Issues', exact: true }).click();
    await page.locator('.issues [role="option"]').first().click();
    await page.getByRole('button', { name: 'Discuss and repair' }).click();
    await page.getByText('Use the project color token and recheck.').waitFor();
    expect(await page.getByLabel('Message the project agent').inputValue()).toContain('Analyze and repair this finding');
    await page.getByText(/Current finding/).waitFor();
    await page.getByRole('button', { name: 'Clear', exact: true }).click();
    expect(await page.getByText(/Current finding/).count()).toBe(0);
    await page.getByRole('button', { name: /Second project/ }).click();
    await page.getByRole('tab', { name: 'Repair chat', exact: true }).click();
    await page.getByText(/Screenshots are attached by default/).waitFor();
    expect(await page.getByRole('checkbox', { name: 'Attach a finding screenshot or page overview' }).isDisabled()).toBe(true);
    await page.getByText(/No screenshot is available for this round/).waitFor();
    expect(await page.getByText('Use the project color token and recheck.').count()).toBe(0);
    await page.getByRole('button', { name: /First project/ }).click();
    await page.getByRole('tab', { name: 'Repair chat', exact: true }).click();
    await page.getByText('Use the project color token and recheck.').waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(await page.getByRole('button', { name: 'Send', exact: true }).isVisible()).toBe(true);
    const sendBox = await page.getByRole('button', { name: 'Send', exact: true }).boundingBox();
    expect(sendBox && sendBox.y + sendBox.height).toBeLessThanOrEqual(844);
  } finally {
    await page.close(); await browser.close(); await server.close();
    await new Promise<void>((done) => model.close(() => done()));
    if (prior === undefined) delete process.env.UXQA_HOME; else process.env.UXQA_HOME = prior;
    await rm(home, { recursive: true, force: true }); await rm(workspace, { recursive: true, force: true });
  }
}, 60_000);
