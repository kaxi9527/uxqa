import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { chromium } from 'playwright';
import { expect, it } from 'vitest';
import { runCheck } from '../src/check/run.js';
import { startConsole } from '../src/ui/server.js';
import { addProject, saveRound } from '../src/ui/store.js';
import { inspectQuality } from '../src/visual/quality.js';

it('uses integrated quality modules and completes issue handling through the real UI', async () => {
  const home = await mkdtemp(join(tmpdir(), 'uxqa-guide-browser-'));
  const priorHome = process.env.UXQA_HOME;
  process.env.UXQA_HOME = home;
  await writeFile(join(home, 'access-settings.json'), JSON.stringify({ locale: 'zh', onboardingDone: true, checks: [] }));
  const entry = await addProject(resolve('examples/check-fixture'), '工作流验证项目');
  const result = await runCheck({ source: entry.root });
  await saveRound(entry.id, result, { roundId: '2026-11-10T00-00-00-000Z' });
  await saveRound(entry.id, result, { roundId: '2026-11-10T00-00-01-000Z' });
  const server = await startConsole({ port: 0 });
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors: string[] = [];
  const page = await context.newPage();
  page.on('pageerror', (error) => errors.push(error.message));
  await context.route('**/*', (route) => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  const evidence = process.env.UXQA_GUIDANCE_EVIDENCE;
  const capture = async (name: string) => {
    if (evidence) {
      await page.waitForFunction(() => document.querySelector('#toast')?.childElementCount === 0);
      await mkdir(evidence, { recursive: true }); await page.screenshot({ path: join(evidence, `${name}.png`) });
    }
  };
  try {
    await page.goto(server.url);
    await page.getByRole('button', { name: /工作流验证项目/ }).click();
    expect(await page.getByRole('button', { name: '内部指南', exact: true }).count()).toBe(0);
    await page.getByRole('tab', { name: '检查', exact: true }).waitFor();
    expect(await page.getByRole('tab', { name: '检查', exact: true }).getAttribute('aria-selected')).toBe('true');
    await page.getByText('最近查看：第 2 轮', { exact: true }).waitFor();
    await capture('checks-desktop');
    await page.getByRole('tab', { name: '问题处理', exact: true }).click();
    await page.getByRole('button', { name: '记录观察', exact: true }).click();
    await page.getByLabel('观察问题名称').fill('切换时缺少反馈');
    await page.getByLabel('观察位置').fill('/settings · 标签页');
    await page.getByLabel('重现步骤与观察证据').fill('快速切换三次，内容停留在旧页；期望每次及时反馈。');
    await page.getByRole('button', { name: '保存观察', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByLabel('问题分类', { exact: true }).selectOption('experience');
    await page.getByText('切换时缺少反馈', { exact: true }).first().waitFor();
    await page.getByText('切换时缺少反馈', { exact: true }).first().click();
    await page.getByRole('button', { name: '处理与分类', exact: true }).click();
    await page.getByLabel('修改处理状态').selectOption('recheck');
    await page.getByLabel('处理理由与验证证据').fill('已增加即时反馈，等待重现原操作验证。');
    await page.getByRole('button', { name: '保存处理记录', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByText('已增加即时反馈，等待重现原操作验证。', { exact: true }).waitFor();
    await capture('issues-desktop');
    await page.getByRole('button', { name: '处理与分类', exact: true }).click();
    expect(await page.getByLabel('处理理由与验证证据').inputValue()).toBe('已增加即时反馈，等待重现原操作验证。');
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: '专项修复方案', exact: true }).click();
    await page.getByLabel('专项诊断目标').selectOption('motion');
    await page.getByLabel('本次诊断目标').fill('验证连续切换，保持已有交互习惯。');
    await page.getByRole('button', { name: '生成并保存', exact: true }).click();
    await page.getByRole('heading', { name: '动效与连续操作', exact: true }).waitFor();
    await page.getByRole('heading', { name: '项目约束与证据边界', exact: true }).waitFor();
    expect(await page.getByRole('dialog').innerText()).toContain('尚未执行');
    expect(await page.getByRole('dialog').innerText()).toContain('验证连续切换');
    await page.getByRole('heading', { name: '项目约束与证据边界', exact: true }).waitFor();
    expect(await page.getByRole('article', { name: '方案内容' }).innerText()).not.toContain('## ');
    await capture('diagnosis-desktop');
    await page.getByRole('button', { name: '逐项验证', exact: true }).click();
    const task = page.locator('.verification-task').first();
    await task.locator(':scope > summary').click();
    await task.getByLabel('验证结果', { exact: true }).selectOption('passed');
    await task.getByRole('button', { name: '保存验证记录', exact: true }).click();
    await task.getByRole('alert').waitFor();
    const evidenceNote = '1440px，在设置页连续打开关闭三次，最终位置与焦点正确。';
    await task.getByLabel('验证过程与证据').fill(evidenceNote);
    await page.route('**/diagnosis/*/verification', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '验证记录暂时无法保存，请重试。' }) }), { times: 1 });
    await task.getByRole('button', { name: '保存验证记录', exact: true }).click();
    await task.getByText('验证记录暂时无法保存，请重试。', { exact: true }).waitFor();
    expect(await task.getByLabel('验证过程与证据').inputValue()).toBe(evidenceNote);
    await task.getByRole('button', { name: '保存验证记录', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '记录通过 1' }).waitFor();
    await task.getByLabel('验证结果', { exact: true }).selectOption('failed');
    await task.getByLabel('验证过程与证据').fill('加入返回操作后，抽屉内容回退到旧位置。');
    await task.getByRole('button', { name: '保存验证记录', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '发现问题 1' }).waitFor();
    await task.getByText('历史记录 · 2', { exact: true }).click();
    expect(await task.locator('.verification-history').innerText()).toContain(evidenceNote);
    await page.getByLabel('筛选验证结果').selectOption('failed');
    await task.locator(':scope > summary').click();
    await capture('verification-desktop');
    expect(await inspectQuality(page, true)).toEqual([]);
    await task.getByRole('button', { name: '转为问题', exact: true }).click();
    expect(await page.getByLabel('重现步骤与观察证据').inputValue()).toContain('抽屉内容回退到旧位置');
    await page.getByLabel('观察问题名称').fill('专项验证转入的问题');
    await page.getByLabel('观察位置').fill('/settings · 抽屉返回');
    await page.getByRole('button', { name: '保存观察', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByText('专项验证转入的问题', { exact: true }).first().waitFor();
    await page.getByRole('button', { name: '专项修复方案', exact: true }).click();
    await page.getByRole('button', { name: /动效与连续操作/ }).click();
    await page.getByRole('heading', { name: '项目约束与证据边界', exact: true }).waitFor();
    expect(await page.getByRole('dialog').innerText()).toContain('验证连续切换');
    await page.keyboard.press('Escape');
    await page.getByRole('tab', { name: '复检', exact: true }).click();
    await page.getByText(/人工标记待复检 1 项/).waitFor();
    expect(await page.getByText('本轮仍然检出', { exact: true }).count()).toBeGreaterThan(0);
    await capture('recheck-desktop');

    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('tab', { name: '检查', exact: true }).click();
    await page.getByRole('heading', { name: '视觉与布局', exact: true }).waitFor();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await capture('checks-mobile');
    expect(await page.locator('body').innerText()).not.toMatch(/Impeccable|Kowalski|Pro Max|完整参考库/);
    await page.getByRole('tab', { name: '问题处理', exact: true }).click();
    await page.getByRole('button', { name: '回到问题列表', exact: true }).click();
    await page.getByRole('button', { name: '专项修复方案', exact: true }).click();
    await page.getByRole('button', { name: /动效与连续操作/ }).click();
    await page.getByRole('heading', { name: '项目约束与证据边界', exact: true }).waitFor();
    await capture('diagnosis-mobile');
    await page.getByRole('button', { name: '逐项验证', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '发现问题 1' }).waitFor();
    await page.getByLabel('筛选验证结果').selectOption('failed');
    await page.locator('.verification-task').first().locator(':scope > summary').click();
    expect(await page.locator('.verification-task').first().getByLabel('验证过程与证据').inputValue()).toContain('抽屉内容回退到旧位置');
    await capture('verification-mobile');
    expect(await inspectQuality(page, true)).toEqual([]);
    expect(await page.getByRole('dialog').evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
    await page.keyboard.press('Escape');
    await page.getByLabel('选择检测轮次').selectOption('2026-11-10T00-00-00-000Z');
    await page.locator('.list-head .delta').filter({ hasText: /检查了/ }).waitFor();
    await page.getByRole('button', { name: '专项修复方案', exact: true }).click();
    await page.getByRole('button', { name: /动效与连续操作/ }).click();
    await page.getByText(/此方案与当前查看的轮次不同/).waitFor();
    await page.keyboard.press('Escape');
    expect(errors).toEqual([]);
  } finally {
    await context.close();
    await browser.close();
    await server.close();
    if (priorHome === undefined) delete process.env.UXQA_HOME; else process.env.UXQA_HOME = priorHome;
    await rm(home, { recursive: true, force: true });
  }
}, 60_000);
