it('respects the configured model request limit and reports an incomplete turn', async () => {
  const home = await mkdtemp(join(tmpdir(), 'uxqa-agent-limit-home-'));
  const projectRoot = await mkdtemp(join(tmpdir(), 'uxqa-agent-limit-project-'));
  const prior = process.env.UXQA_HOME;
  process.env.UXQA_HOME = home;
  let calls = 0;
  const model = createServer((_request, response) => { calls++; response.setHeader('content-type', 'application/json'); response.end(JSON.stringify({ choices: [{ message: { content: JSON.stringify({ type: 'list', path: '' }) } }] })); });
  await new Promise<void>((done) => model.listen(0, '127.0.0.1', done));
  const address = model.address();
  if (!address || typeof address === 'string') throw new Error('Expected local model fixture');
  try {
    const project = await addProject(projectRoot, 'Budget fixture');
    await writeAiSettings({ mode: 'api', protocol: 'openai', connection: 'direct', baseUrl: `http://127.0.0.1:${address.port}/v1`, model: 'fixture', passes: 1, verify: false, discover: false, maxCalls: 2 });
    await startProjectAgent(project, { text: 'Inspect this UI' });
    let state = await getProjectAgent(project.id);
    for (let i = 0; state.running && i < 100; i++) { await new Promise((done) => setTimeout(done, 20)); state = await getProjectAgent(project.id); }
    expect(state.running).toBe(false);
    expect(calls).toBe(2);
    expect(state.messages.at(-1)?.text).toContain('操作次数上限');
  } finally {
    await stopProjectAgents();
    await new Promise<void>((done) => model.close(() => done()));
    if (prior === undefined) delete process.env.UXQA_HOME; else process.env.UXQA_HOME = prior;
    await rm(home, { recursive: true, force: true }); await rm(projectRoot, { recursive: true, force: true });
  }
}, 30_000);

it('rejects a duplicate project task and stops an in-flight model request', async () => {
  const home = await mkdtemp(join(tmpdir(), 'uxqa-agent-cancel-home-'));
  const projectRoot = await mkdtemp(join(tmpdir(), 'uxqa-agent-cancel-project-'));
  const prior = process.env.UXQA_HOME;
  process.env.UXQA_HOME = home;
  let arrived!: () => void;
  const requestArrived = new Promise<void>((done) => { arrived = done; });
  const model = createServer((_request, response) => { arrived(); response.on('close', () => response.end()); });
  await new Promise<void>((done) => model.listen(0, '127.0.0.1', done));
  const address = model.address();
  if (!address || typeof address === 'string') throw new Error('Expected local model fixture');
  try {
    const project = await addProject(projectRoot, 'Cancellation fixture');
    await writeAiSettings({ mode: 'api', protocol: 'openai', connection: 'direct', baseUrl: `http://127.0.0.1:${address.port}/v1`, model: 'fixture', passes: 1, verify: false, discover: false, maxCalls: 8 });
    await startProjectAgent(project, { text: 'Inspect this UI' });
    await requestArrived;
    await expect(startProjectAgent(project, { text: 'Duplicate' })).rejects.toMatchObject({ status: 409 });
    cancelProjectAgent(project.id);
    let state = await getProjectAgent(project.id);
    for (let i = 0; state.running && i < 100; i++) { await new Promise((done) => setTimeout(done, 20)); state = await getProjectAgent(project.id); }
    expect(state.running).toBe(false);
    expect(state.messages.at(-1)?.text).toContain('已停止');
  } finally {
    await stopProjectAgents();
    await new Promise<void>((done) => model.close(() => done()));
    if (prior === undefined) delete process.env.UXQA_HOME; else process.env.UXQA_HOME = prior;
    await rm(home, { recursive: true, force: true }); await rm(projectRoot, { recursive: true, force: true });
  }
}, 30_000);
