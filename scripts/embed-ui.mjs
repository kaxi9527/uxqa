// Regenerates src/ui/assets.ts from src/ui/web so the console works from tsc output and single-file builds alike.
// Run after editing anything in src/ui/web:  node scripts/embed-ui.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = [['/index.html', 'index.html', 'text/html; charset=utf-8'], ['/app.css', 'app.css', 'text/css; charset=utf-8'], ['/workflow.js', 'workflow.js', 'text/javascript; charset=utf-8'], ['/access.js', 'access.js', 'text/javascript; charset=utf-8'], ['/app.js', 'app.js', 'text/javascript; charset=utf-8']];
const entries = [];
const icon = await readFile(join(root, 'assets/icon-256.png'));
entries.push(`  "/icon.png": { type: "image/png", body: ${JSON.stringify(icon.toString('base64'))}, encoding: "base64" },`);
for (const [route, name, type] of files) {
  const body = await readFile(join(root, 'src/ui/web', name), 'utf8');
  entries.push(`  ${JSON.stringify(route)}: { type: ${JSON.stringify(type)}, body: ${JSON.stringify(body)} },`);
}
const output = `// Generated by scripts/embed-ui.mjs from src/ui/web. Do not edit by hand.\nexport const ASSETS: Record<string, { type: string; body: string; encoding?: 'base64' }> = {\n${entries.join('\n')}\n};\n`;
await writeFile(join(root, 'src/ui/assets.ts'), output);
console.log(`src/ui/assets.ts: ${files.length} files`);
